"""
Оркестратор ETL-процесса для проекта "IMDb Explorer".

Этот скрипт выполняет роль центрального управляющего модуля для инженерии данных и генерации дашборда:
1.  **Extract:** Загрузить "сырые" данные из исходного CSV-файла.
2.  **Transform:** Провести базовую проверку данных (в данном случае, просто убедиться, что они существуют).
3.  **Load:** Загрузить очищенные данные в структурированную базу данных SQLite.
4.  **Present:** Создать интерактивный и понятный дашборд на основе очищенных данных
"""

import sqlite3
import pandas as pd
import os

# Импортируем конфигурацию и утилиты
import config
from db_utils import write_df_to_table
from dashboard_core import run_dashboard


def main():
    """Главная функция, запускающая ETL-пайплайн."""

    print("--- Запуск ETL-пайплайна для подготовки данных ---")

    # --- EXTRACT ---
    # Проверяем, существует ли исходный CSV-файл, прежде чем продолжить.
    # Это базовая валидация данных на входе.
    if not os.path.exists(config.CSV_PATH):
        print(f"[ОШИБКА] Исходный файл данных '{config.CSV_PATH}' не найден.")
        print("Пожалуйста, убедитесь, что файл находится в корневой папке проекта.")
        return  # Прерываем выполнение, если данных нет

    print(f"Шаг 1/3: Исходный файл '{config.CSV_PATH}' успешно найден.")
    df = pd.read_csv(config.CSV_PATH)

    # --- TRANSFORM ---
    # На данном этапе трансформация минимальна, так как основная очистка
    # и преобразование типов делегированы утилитам, вызываемым из дашборда.
    # Здесь могла бы быть сложная логика очистки, если бы она требовалась на этапе загрузки.
    print("Шаг 2/3: Трансформация данных (пропущена, выполняется в рантайме).")

    # --- LOAD ---
    # Используем 'try-except-finally' для безопасной работы с базой данных.
    # 'with' менеджер контекста автоматически управляет транзакциями.
    conn = None
    try:
        # Устанавливаем соединение с базой данных
        conn = sqlite3.connect(config.DB_PATH)
        print(
            f"Шаг 3/3: Загрузка данных в таблицу '{config.TABLE_NAME}' базы данных '{config.DB_PATH}'..."
        )

        # Вызываем утилиту для записи DataFrame в SQL-таблицу
        write_df_to_table(conn, df, config.TABLE_NAME)

        print("\n[УСПЕХ] База данных успешно создана и наполнена.")

    except sqlite3.Error as e:
        print(f"\n[КРИТИЧЕСКАЯ ОШИБКА] Произошла ошибка при работе с базой данных: {e}")

    finally:
        # Гарантируем, что соединение будет закрыто, даже если произошла ошибка
        if conn:
            conn.close()


if __name__ == "__main__":
    main()
    run_dashboard()
